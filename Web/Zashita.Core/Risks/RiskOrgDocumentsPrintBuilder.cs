    public static string Title(string kind) => Normalize(kind) switch
    {
        Measures => "Перечень мер управления рисками",
        IdentificationCards => "Карты идентификации рисков",
        TitlePage => "Титульный лист",
        Regulation => "Положение (методика)",
        Methodology => "Титульный лист и положение",
        _ => "Документ ОПР"
    };

    public static string Normalize(string? kind) => (kind ?? string.Empty).Trim().ToLowerInvariant() switch
    {
        "measures" or "меры" or "перечень мер" => Measures,
        "identification" or "identification-cards" or "карты" or "карты идентификации" => IdentificationCards,
        "title" or "title-page" or "титул" or "титульный" or "титульный лист" => TitlePage,
        "regulation" or "положение" or "методика" or "method" => Regulation,
        "methodology" or "титульный лист и положение" => Methodology,
        _ => TitlePage
    };

    public static string Build(
        string kind,
        string organization,
        IReadOnlyList<OrganizationEmployee>? employees = null,
        IReadOnlyList<RiskHazardCatalogItem>? hazards = null,
        IReadOnlyList<WorkplaceRecord>? workplaces = null,
        IReadOnlyDictionary<string, string>? overrides = null,
        string? regulationHtml = null)
    {
        var ov = overrides is null
            ? new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
            : new Dictionary<string, string>(overrides, StringComparer.OrdinalIgnoreCase);
        var director = Resolve(ov, "org-manager", RiskPrintChrome.ResolveDirectorSignInitials(organization, employees));
        var orgName = Resolve(ov, "org-name", organization);

        return Normalize(kind) switch
        {
            Measures => BuildMeasures(orgName, director, hazards ?? [], ov),
            IdentificationCards => BuildIdentificationCards(orgName, director, workplaces ?? [], ov),
            TitlePage => BuildTitlePage(orgName, director, ov, employees),
            Regulation => BuildRegulation(orgName, director, ov, regulationHtml),
            Methodology => BuildTitlePage(orgName, director, ov, employees)
                           + """<div class="risks-page-break"></div>"""
                           + BuildRegulation(orgName, director, ov, regulationHtml),
            _ => BuildTitlePage(orgName, director, ov, employees)
        };
    }

