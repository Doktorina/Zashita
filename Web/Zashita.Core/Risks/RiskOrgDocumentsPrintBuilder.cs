            <p class="risks-order-preamble"><b>7.1.</b> Управление рисками выполнено с учетом рекомендаций Приказа Минтруда России от 28.12.2021 № 926 «Об утверждении Рекомендаций по выбору методов оценки уровней профессиональных рисков и по снижению уровней таких рисков».</p>
