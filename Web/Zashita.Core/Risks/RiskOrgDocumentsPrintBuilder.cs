    private static string Cell(Dictionary<string, string> ov, string key, string value)
    {
        var text = Resolve(ov, key, value);
        return $"<span contenteditable=\"true\" data-override-key=\"{Web(key)}\">{Web(text)}</span>";
    }

    private static string Resolve(Dictionary<string, string> ov, string key, string? fallback)
    {
        if (ov.TryGetValue(key, out var v) && !string.IsNullOrWhiteSpace(v))
        {
            return v;
        }

        return fallback ?? string.Empty;
    }

    private static string Web(string? value) => WebUtility.HtmlEncode(value ?? string.Empty);
