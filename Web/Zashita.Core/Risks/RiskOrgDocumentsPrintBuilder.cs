    public static string ApplyPlaceholders(string html, string organization, string director, string? assessDate = null)
    {
        var text = html ?? string.Empty;
        var org = organization?.Trim() ?? string.Empty;
        var dir = director?.Trim() ?? string.Empty;
        var date = string.IsNullOrWhiteSpace(assessDate) ? DateTime.Today.ToString("dd.MM.yyyy") : assessDate.Trim();

        // Пустое значение не затирает плейсхолдер (иначе при «Все» пропадает организация).
        text = ReplacePlaceholder(text, "Организация", org);
        text = ReplacePlaceholder(text, "OrgName", org);
        text = ReplacePlaceholder(text, "org", org);
        text = ReplacePlaceholder(text, "Руководитель", dir);
        text = ReplacePlaceholder(text, "director", dir);
        text = ReplacePlaceholder(text, "Дата", date);
        text = ReplacePlaceholder(text, "date", date);
        return text;
    }

    private static string ReplacePlaceholder(string input, string name, string value)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            return input;
        }

        foreach (var token in new[]
                 {
                     "{{" + name + "}}",
                     "{{ " + name + " }}",
                     "{" + name + "}",
                     "[[" + name + "]]"
                 })
        {
            input = Regex.Replace(input, Regex.Escape(token), value, RegexOptions.IgnoreCase | RegexOptions.CultureInvariant);
        }

        return input;
    }

